export function route(locale: Locale, path = ''): string {
  return `${locale === 'tr' ? '/tr' : ''}/${path ? `${path}/` : ''}`;
}
export function alternate(pathname: string, locale: Locale): string {
  return route(
    locale,
    pathname.replace(/^\/tr(?=\/|$)/, '').replace(/^\/|\/$/g, ''),
  );
}
